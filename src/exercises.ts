import type {
  Category,
  Equipment,
  Exercise,
  Intensity,
  Level,
  Role,
  Unit,
} from './types.ts'

function ex(
  id: string,
  name: string,
  category: Category,
  level: Level,
  intensity: Intensity,
  role: Role,
  easier: string,
  equipment: readonly Equipment[] = ['boden'],
  unit: Unit = 'wdh',
): Exercise {
  return { id, name, category, equipment, level, unit, intensity, role, easier }
}

